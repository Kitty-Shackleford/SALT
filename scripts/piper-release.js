#!/usr/bin/env node
// Piper — simple release helper: create annotated git tag and print release notes

const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

function run(cmd) {
  try { return execSync(cmd, { stdio: 'pipe' }).toString().trim(); } catch (e) { return ''; }
}

const RELEASE_VERSION = process.env.RELEASE_VERSION || process.argv[2] || '';

let version = RELEASE_VERSION;
if (!version) {
  // try from root package.json
  try {
    const pkg = JSON.parse(fs.readFileSync(path.join(process.cwd(), 'package.json'), 'utf8'));
    if (pkg && pkg.version) version = pkg.version;
  } catch (e) {}
}

if (!version) {
  console.error('Piper: no release version found. Provide RELEASE_VERSION env var or pass as argument.');
  process.exit(1);
}

const tag = version.startsWith('v') ? version : `v${version}`;

// ensure working tree is clean
const status = run('git status --porcelain');
if (status) {
  console.error('Piper: working tree is not clean; please commit or stash changes before tagging.');
  process.exit(2);
}

// create annotated tag
console.log(`Piper: creating tag ${tag}`);
const msg = `Release ${tag} — generated by Piper`;
run(`git tag -a ${tag} -m "${msg}"`);

// push tag
console.log('Piper: pushing tag to origin');
const pushOut = run(`git push origin ${tag}`);
console.log(pushOut);

// generate simple release notes (commits since last tag)
let prev = '';
try { prev = run(`git describe --tags --abbrev=0 ${tag}^ 2>/dev/null`); } catch (e) { prev = ''; }
let range = prev ? `${prev}..${tag}` : `${tag}`;
const logCmd = `git log ${range} --no-merges --pretty=format:%s (%h) --reverse`;
const log = run(logCmd);

console.log('\n=== Piper Release Notes ===\n');
if (!log) {
  console.log('No commits to show for this release.');
} else {
  console.log(log.split('\n').map(l => `- ${l}`).join('\n'));
}
console.log('\nRelease tag created: ' + tag);

console.log('\nNext: run the CI workflow to build and publish images (if configured).');
process.exit(0);
